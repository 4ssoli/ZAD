ZAD.resourcesFor = function (slug) {
  return ZAD.RESOURCES[slug] || [];
};
ZAD.startPathFor = function (slug) {
  return ZAD.resourcesFor(slug).filter(r => r.step).sort((a, b) => a.step - b.step);
};
